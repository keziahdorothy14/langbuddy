// ── Detail study and test screen for local-industry vocabulary ──
class IndustryStudyScreen extends StatefulWidget {
  final String title;
  final List<CommunityWord> words;
  final Color color;
  final String targetLanguage;

  const IndustryStudyScreen({
    super.key,
    required this.title,
    required this.words,
    required this.color,
    required this.targetLanguage,
  });

  @override
  State<IndustryStudyScreen> createState() => _IndustryStudyScreenState();
}

class _IndustryStudyScreenState extends State<IndustryStudyScreen> {
  bool isTestingMode = false;
  int currentQuestionIndex = 0;
  int score = 0;
  List<String> options = [];
  String correctAnswer = "";

  void _startQuiz() {
    setState(() {
      isTestingMode = true;
      currentQuestionIndex = 0;
      score = 0;
      _setupQuestion();
    });
  }

  void _setupQuestion() {
    final rand = Random();
    final currentWord = widget.words[currentQuestionIndex];
    correctAnswer =
        currentWord.translations[widget.targetLanguage] ?? currentWord.word;

    // Generate 3 random wrong options from this or other lists
    List<String> allWrong = [];
    for (var w in widget.words) {
      String trans = w.translations[widget.targetLanguage] ?? w.word;
      if (trans != correctAnswer) allWrong.add(trans);
    }

    // Add extra generic placeholders if we don't have enough
    while (allWrong.length < 2) {
      allWrong.add("Placholder-${rand.nextInt(100)}");
    }

    allWrong.shuffle();
    options = [correctAnswer, ...allWrong.take(2)]..shuffle();
  }

  void _answerQuestion(String selected) {
    if (selected == correctAnswer) score++;

    if (currentQuestionIndex < widget.words.length - 1) {
      setState(() {
        currentQuestionIndex++;
        _setupQuestion();
      });
    } else {
      // Completed
      showDialog(
        context: context,
        barrierDismissible: false,
        builder: (_) => AlertDialog(
          title: const Text("Industry Pack Complete!"),
          content: Text(
              "You scored $score / ${widget.words.length} in ${widget.title} Quiz."),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.pop(context);
                setState(() {
                  isTestingMode = false;
                });
              },
              child: const Text("Study More"),
            ),
          ],
        ),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;

    return Scaffold(
      backgroundColor:
          isDark ? const Color(0xFF0F0F1E) : const Color(0xFFF4F6FF),
      appBar: AppBar(
        title: Text(widget.title),
        backgroundColor: widget.color,
        actions: [
          IconButton(
            icon: Icon(isTestingMode ? Icons.menu_book : Icons.quiz_rounded),
            onPressed: isTestingMode
                ? () => setState(() => isTestingMode = false)
                : _startQuiz,
          ),
        ],
      ),
      body: isTestingMode ? _buildQuizView(isDark) : _buildStudyView(isDark),
    );
  }

  Widget _buildStudyView(bool isDark) {
    return ListView.builder(
      padding: const EdgeInsets.all(16),
      itemCount: widget.words.length,
      itemBuilder: (context, index) {
        final item = widget.words[index];
        final trans = item.translations[widget.targetLanguage] ?? item.word;
        final phonetic = getPhoneticHint(item.word);

        return Card(
          margin: const EdgeInsets.only(bottom: 14),
          elevation: 3,
          shape:
              RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
          color: isDark ? const Color(0xFF1E1E32) : Colors.white,
          child: ListTile(
            contentPadding: const EdgeInsets.all(16),
            title: Row(
              children: [
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
